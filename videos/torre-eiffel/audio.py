"""Audio de 'El hombre que vendió la Torre Eiffel'. Uso: python3 audio.py carpeta_voz salida.wav"""
import sys; sys.path.insert(0, '../lib')
from sonido import Mezcla
A = Mezcla(estilo='paris')
c = A.cap
A.fx(A.paper(), A.ST[0] + .2, .6); A.fx(A.stamp(), c(0, 2) + .3, .9); A.fx(A.wink(), c(0, 3), .7)
A.fx(A.pop(600), A.ST[1] + .3, .5); A.fx(A.stamp(), c(1, 1), .8); A.fx(A.paper(), c(1, 2) - .2, .8)
for k in range(10): A.fx(A.paper(), c(1, 5) + k * .06, .4, (k % 3 - 1) * .5)
A.fx(A.register(), c(1, 5), .6)
A.fx(A.whoosh(.4), A.ST[2] + .9, .6); A.fx(A.pop(800), c(2, 1), .5)
A.fx(A.bell(1046), c(2, 3) - .2, .4); A.fx(A.pop(600), c(2, 4), .5)
for k in range(8): A.fx(A.knock(), c(3, 2) + k * .14, .4, (k % 3 - 1) * .5)
A.fx(A.stamp(), c(3, 5), .9); A.fx(A.shh(), c(3, 5) + .2, .6)
A.fx(A.pop(500), c(4, 1), .5); A.fx(A.ding(), c(4, 2), .5); A.fx(A.whoosh(.5), c(4, 3) - .3, .5); A.fx(A.register(), c(4, 3) + .5, .7)
A.fx(A.paper(), c(4, 5) - .3, .7); A.fx(A.wink(), c(4, 5) + .1, .6)
A.fx(A.train(c(5, 1) - A.ST[5]), A.ST[5], .6); A.fx(A.bell(880), A.ST[5] + .2, .4)
A.fx(A.sad(), c(5, 2), .5); A.fx(A.stamp(), c(5, 3), .6)
for k in range(5): A.fx(A.step(), A.ST[6] + k * .25, .5)
A.fx(A.stamp(), c(6, 3), .9); A.fx(A.fanfare(), c(6, 3) + .1, .5)
whistle = A.mix(A.tone(2800, .9, 2, (1, .1)) * .4)
A.fx(whistle, A.ST[7] + .3, .6)
for k in range(16): A.fx(A.step(), A.ST[7] + k * .26, .45, (k % 2) * .4 - .2)
A.fx(A.pop(900), c(7, 2), .7); A.fx(A.ding(), c(7, 2) + .05, .5)
A.guardar(sys.argv[1], sys.argv[2])
